import Foundation

/// Generates the as-built report after an Apply: every deployed item with its
/// settings payload and assignment, plus prerequisites and per-step results.
nonisolated enum AsBuiltReport {
    struct Input: Sendable {
        let profileName: String
        let tenantID: String
        let namingPrefix: String
        let plan: Plan
        let results: [ApplyResult]
        let date: Date
        /// The profile's variables: their values (over four characters) are
        /// masked in the Apply steps' titles and messages, which can repeat
        /// an item's name or a value Graph refused. Names and payloads are
        /// masked by the plan (`PlanItemAction.reportName`, `reportPayload`).
        var variables: [String: String] = [:]

        /// A step's title or message with variable values over four
        /// characters masked (shorter ones would hide ordinary words).
        func masked(_ text: String) -> String {
            AsBuiltReport.masking(text, values: Array(variables.values), minimumLength: 5)
        }
    }

    /// What stands where a variable's value is: a baseline keeps its secrets
    /// (a Wi-Fi password, an API key) in variables. Only those places are
    /// masked, inside base64 content too; the same text elsewhere isn't.
    static let mask = "••••"

    /// `text` with every value of at least `minimumLength` characters
    /// replaced by the mask, longest first.
    static func masking(_ text: String, values: [String], minimumLength: Int) -> String {
        values.map { $0.trimmingCharacters(in: .whitespacesAndNewlines) }
            .filter { $0.count >= minimumLength }
            .sorted { $0.count > $1.count }
            .reduce(text) { $0.replacingOccurrences(of: $1, with: mask) }
    }

    /// Said above the items, in both reports.
    static let maskingNote = "Variable values are masked (••••) where a variable is used."

    // MARK: - Markdown

    static func markdown(_ input: Input) -> String {
        var lines: [String] = []
        let date = input.date.formatted(date: .long, time: .shortened)
        lines.append("# As-Built Report — \(input.profileName)")
        lines.append("")
        lines.append("Generated by Intune Deployer on \(date).")
        lines.append("")
        lines.append("| | |")
        lines.append("| --- | --- |")
        lines.append("| Tenant ID | `\(input.tenantID)` |")
        lines.append("| Naming prefix | \(input.namingPrefix.isEmpty ? "none" : input.namingPrefix) |")
        lines.append("| Result | \(resultSummary(input.results)) |")
        lines.append("")

        if !input.plan.groupsToCreate.isEmpty || !input.plan.filtersToCreate.isEmpty {
            lines.append("## Prerequisites")
            lines.append("")
            for group in input.plan.groupsToCreate {
                lines.append("- Entra security group **\(mdEscape(group.name))**")
            }
            for filter in input.plan.filtersToCreate {
                lines.append("- Assignment filter **\(mdEscape(filter.name))** — rule: `\(filter.rule.replacingOccurrences(of: "`", with: "'"))`")
            }
            lines.append("")
        }

        lines.append("## Items")
        lines.append("")
        lines.append(maskingNote)
        lines.append("")
        for action in input.plan.actions {
            lines.append("### \(mdEscape(action.reportName ?? action.displayName))")
            lines.append("")
            lines.append("| | |")
            lines.append("| --- | --- |")
            lines.append("| Type | \(action.collection.displayName) |")
            lines.append("| Action | \(action.kind.label) |")
            lines.append("| Assignment | \(mdEscape(assignmentDescription(action.assignments))) |")
            lines.append("| Identity tag | `\(ItemIdentity.tag(forShortID: action.id))` |")
            lines.append("")
            for warning in action.warnings {
                lines.append("> Warning: \(mdEscape(warning))")
                lines.append("")
            }
            lines.append("<details><summary>Settings payload</summary>")
            lines.append("")
            lines.append("```json")
            lines.append(payloadText(action))
            lines.append("```")
            lines.append("")
            lines.append("</details>")
            lines.append("")
        }

        lines.append("## Apply Steps")
        lines.append("")
        lines.append("| Step | Result |")
        lines.append("| --- | --- |")
        for result in input.results {
            lines.append("| \(mdEscape(input.masked(result.title))) | \(mdEscape(input.masked(outcomeText(result.outcome)))) |")
        }
        lines.append("")
        return lines.joined(separator: "\n")
    }

    /// Baseline-controlled text in the Markdown report: neutralize inline
    /// HTML and table/formatting metacharacters (the HTML report has its own
    /// escaping).
    private static func mdEscape(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "|", with: "\\|")
            .replacingOccurrences(of: "`", with: "\\`")
    }

    // MARK: - HTML

    static func html(_ input: Input) -> String {
        let date = input.date.formatted(date: .long, time: .shortened)
        var body = ""
        body += "<h1>As-Built Report — \(escape(input.profileName))</h1>"
        body += "<p class=\"meta\">Generated by Intune Deployer on \(escape(date)).</p>"
        body += "<table><tr><th>Tenant ID</th><td><code>\(escape(input.tenantID))</code></td></tr>"
        body += "<tr><th>Naming prefix</th><td>\(escape(input.namingPrefix.isEmpty ? "none" : input.namingPrefix))</td></tr>"
        body += "<tr><th>Result</th><td>\(escape(resultSummary(input.results)))</td></tr></table>"

        if !input.plan.groupsToCreate.isEmpty || !input.plan.filtersToCreate.isEmpty {
            body += "<h2>Prerequisites</h2><ul>"
            for group in input.plan.groupsToCreate {
                body += "<li>Entra security group <strong>\(escape(group.name))</strong></li>"
            }
            for filter in input.plan.filtersToCreate {
                body += "<li>Assignment filter <strong>\(escape(filter.name))</strong> — rule: <code>\(escape(filter.rule))</code></li>"
            }
            body += "</ul>"
        }

        body += "<h2>Items</h2><p class=\"meta\">\(escape(maskingNote))</p>"
        for action in input.plan.actions {
            body += "<section><h3>\(escape(action.reportName ?? action.displayName))</h3>"
            body += "<table>"
            body += "<tr><th>Type</th><td>\(escape(action.collection.displayName))</td></tr>"
            body += "<tr><th>Action</th><td>\(escape(action.kind.label))</td></tr>"
            body += "<tr><th>Assignment</th><td>\(escape(assignmentDescription(action.assignments)))</td></tr>"
            body += "<tr><th>Identity tag</th><td><code>\(escape(ItemIdentity.tag(forShortID: action.id)))</code></td></tr>"
            body += "</table>"
            for warning in action.warnings {
                body += "<p class=\"warning\">Warning: \(escape(warning))</p>"
            }
            body += "<details><summary>Settings payload</summary><pre>\(escape(payloadText(action)))</pre></details>"
            body += "</section>"
        }

        body += "<h2>Apply Steps</h2><table><tr><th>Step</th><th>Result</th></tr>"
        for result in input.results {
            body += "<tr><td>\(escape(input.masked(result.title)))</td><td>\(escape(input.masked(outcomeText(result.outcome))))</td></tr>"
        }
        body += "</table>"

        return """
        <!DOCTYPE html>
        <html lang="en"><head><meta charset="utf-8">
        <title>As-Built Report — \(escape(input.profileName))</title>
        <style>
        body { font: 14px -apple-system, system-ui, sans-serif; max-width: 920px; margin: 2rem auto; padding: 0 1rem; color: #1d1d1f; }
        h1, h2, h3 { font-weight: 600; }
        table { border-collapse: collapse; margin: 0.5rem 0 1rem; }
        th, td { text-align: left; padding: 4px 12px; border-bottom: 1px solid #e5e5e7; vertical-align: top; }
        th { color: #6e6e73; font-weight: 500; white-space: nowrap; }
        code, pre { font: 12px ui-monospace, monospace; background: #f5f5f7; border-radius: 4px; }
        code { padding: 1px 4px; }
        pre { padding: 10px; overflow-x: auto; }
        details { margin: 0.5rem 0 1rem; }
        summary { cursor: pointer; color: #0066cc; }
        .meta { color: #6e6e73; }
        .warning { color: #9a6700; }
        section { margin-bottom: 1.5rem; }
        </style></head><body>\(body)</body></html>
        """
    }

    // MARK: - Shared helpers

    static func assignmentDescription(_ assignments: [ResolvedAssignment]?) -> String {
        guard let assignments else { return "Left unchanged" }
        guard !assignments.isEmpty else { return "No targets" }
        return assignments.map(targetDescription).joined(separator: "; ")
    }

    static func targetDescription(_ assignment: ResolvedAssignment) -> String {
        var text: String
        switch assignment.target {
        case .allDevices: text = "All devices"
        case .allUsers: text = "All users"
        case .group(_, let name): text = "Group “\(name)”"
        }
        if assignment.isExclusion {
            // Exclusions always target a group.
            if case .group(_, let name) = assignment.target { return "Excluding group “\(name)”" }
            return "Excluding \(text)"
        }
        if let filter = assignment.filter {
            let name: String
            switch filter {
            case .existing: name = "existing filter"
            case .pendingCreation(let filterName): name = "“\(filterName)”"
            }
            text += " with \(assignment.filterMode.rawValue) filter \(name)"
        }
        if assignment.appIntent == .available {
            text += " (available in Company Portal)"
        }
        return text
    }

    private static func resultSummary(_ results: [ApplyResult]) -> String {
        let failures = results.count(where: \.isFailure)
        let successes = results.count { if case .success = $0.outcome { true } else { false } }
        if results.isEmpty { return "No steps were executed" }
        if failures == 0 {
            return "\(successes) of \(results.count) step\(results.count == 1 ? "" : "s") succeeded"
        }
        return "\(failures) of \(results.count) steps failed"
    }

    private static func outcomeText(_ outcome: ApplyResult.Outcome) -> String {
        switch outcome {
        case .success: "Succeeded"
        case .failure(let message): "Failed: \(message)"
        case .skipped(let reason): "Skipped: \(reason)"
        // the message starts with "Stopped" and says whether it may have been done
        case .stopped(let message): message
        }
    }

    /// The payload as the report shows it (see `PlanItemAction.reportPayload`).
    static func payloadText(_ action: PlanItemAction) -> String {
        switch action.reportPayload {
        case .same: prettyPayload(action.payload)
        case .masked(let masked): prettyPayload(masked)
        case .leftOut: "(Left out: it holds variable values that can’t be masked here.)"
        }
    }

    static func prettyPayload(_ payload: Data) -> String {
        guard let object = try? JSONSerialization.jsonObject(with: payload),
              let pretty = try? JSONSerialization.data(withJSONObject: object, options: [.prettyPrinted, .sortedKeys]),
              let text = String(data: pretty, encoding: .utf8) else {
            return String(data: payload, encoding: .utf8) ?? "(binary)"
        }
        return text
    }

    static func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "&", with: "&amp;")
            .replacingOccurrences(of: "<", with: "&lt;")
            .replacingOccurrences(of: ">", with: "&gt;")
            .replacingOccurrences(of: "\"", with: "&quot;")
    }
}
